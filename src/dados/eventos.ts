/** Encaixa cada modelo na única data da janela que cai no seu dia da semana. */
export function gerarEventosDaSemana(dias: readonly string[]): Evento[] {
  return MODELOS.flatMap(({ diaSemana, ...campos }) => {
    const data = dias.find((dia) => diaDaSemana(dia) === diaSemana);
    return data ? [{ ...campos, data, novo: false }] : [];
  });
}
